package com.pcbqms.workorder.api;

import com.pcbqms.workorder.domain.ProductionBatch;
import com.pcbqms.workorder.domain.WorkOrder;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

public record WorkOrderResponse(
    String id,
    String workOrderNo,
    String productCode,
    String productName,
    String specification,
    String currentProcessCode,
    String currentProcessName,
    Integer plannedQuantity,
    Integer completedQuantity,
    String priority,
    String processRouteVersion,
    String miVersion,
    String qualityStatus,
    String sourceSystem,
    String sourceKey,
    String sourceVersion,
    String status,
    String customerCode,
    String internalProductNo,
    String customerPartNo,
    String processTechnology,
    String material,
    String boardThickness,
    String copperThickness,
    String warehouseStatus,
    LocalDate releasedAt,
    LocalDate materialInputDate,
    BigDecimal pcsLength,
    BigDecimal pcsWidth,
    String materialNo,
    String materialName,
    String materialSpecification,
    BigDecimal standardMaterialConsumption,
    Integer cumulativeWarehouseQuantity,
    LocalDate requiredDeliveryDate,
    String productionNoticeNo,
    LocalDate inputDate,
    BigDecimal singlePcsArea,
    BigDecimal aBoardLength,
    BigDecimal aBoardWidth,
    BigDecimal bBoardLength,
    BigDecimal bBoardWidth,
    String formingMethod,
    Integer layerCount,
    Integer productionNoticeQuantity,
    String customerOrder,
    String customerOrderNo,
    Integer customerOrderQuantity,
    BigDecimal materialArea,
    BigDecimal productionNoticeArea,
    BigDecimal customerOrderArea,
    Integer totalPanelQuantity,
    Integer aBoardPanelQuantity,
    Integer bBoardPanelQuantity,
    String panelizationNo,
    BigDecimal estimatedYieldRate,
    BigDecimal plannedMaterialIssueQuantity,
    LocalDateTime updatedAt,
    List<BatchResponse> batches,
    Integer materialInputQuantity,
    Integer cumulativeScrapQuantity,
    Integer cumulativeDefectQuantity,
    BigDecimal pnlLength,
    BigDecimal pnlWidth,
    Integer productionNoticeOrderQuantity,
    Integer unreceivedQuantity,
    LocalDate lastWarehouseDate
) {
    /** Compatibility constructor for integrations that only consume the original work-order fields. */
    public WorkOrderResponse(
        String id,
        String workOrderNo,
        String productCode,
        String productName,
        String specification,
        String currentProcessCode,
        String currentProcessName,
        Integer plannedQuantity,
        Integer completedQuantity,
        String sourceSystem,
        String status,
        String customerCode,
        String internalProductNo,
        String customerPartNo,
        String processTechnology,
        String material,
        String boardThickness,
        String copperThickness,
        String warehouseStatus,
        LocalDate releasedAt,
        LocalDateTime updatedAt,
        List<BatchResponse> batches
    ) {
        this(id, workOrderNo, productCode, productName, specification, currentProcessCode, currentProcessName,
            plannedQuantity, completedQuantity, null, null, null, null, sourceSystem, null, null, status, customerCode, internalProductNo, customerPartNo,
            processTechnology, material, boardThickness, copperThickness, warehouseStatus, releasedAt,
            null, null, null, null, null, null, null, null, null, null,
            null, null, null, null, null, null, null, null, null, null,
            null, null, null, null, null, null, null, null, null, null, null,
            updatedAt, batches, null, null, null, null, null, null, null, null);
    }

    public static WorkOrderResponse from(WorkOrder workOrder, List<ProductionBatch> batches) {
        return new WorkOrderResponse(
            workOrder.getId(),
            workOrder.getWorkOrderNo(),
            workOrder.getProductCode(),
            workOrder.getProductName(),
            workOrder.getSpecification(),
            workOrder.getCurrentProcessCode(),
            workOrder.getCurrentProcessName(),
            workOrder.getPlannedQuantity(),
            workOrder.getCompletedQuantity(),
            workOrder.getPriority(),
            workOrder.getProcessRouteVersion(),
            workOrder.getMiVersion(),
            workOrder.getQualityStatus(),
            workOrder.getSourceSystem(),
            workOrder.getSourceKey(),
            workOrder.getSourceVersion(),
            workOrder.getStatus(),
            workOrder.getCustomerCode(),
            workOrder.getInternalProductNo(),
            workOrder.getCustomerPartNo(),
            workOrder.getProcessTechnology(),
            workOrder.getMaterial(),
            workOrder.getBoardThickness(),
            workOrder.getCopperThickness(),
            workOrder.getWarehouseStatus(),
            workOrder.getReleasedAt(),
            workOrder.getMaterialInputDate(),
            workOrder.getPcsLength(),
            workOrder.getPcsWidth(),
            workOrder.getMaterialNo(),
            workOrder.getMaterialName(),
            workOrder.getMaterialSpecification(),
            workOrder.getStandardMaterialConsumption(),
            workOrder.getCumulativeWarehouseQuantity(),
            workOrder.getRequiredDeliveryDate(),
            workOrder.getProductionNoticeNo(),
            workOrder.getInputDate(),
            workOrder.getSinglePcsArea(),
            workOrder.getABoardLength(),
            workOrder.getABoardWidth(),
            workOrder.getBBoardLength(),
            workOrder.getBBoardWidth(),
            workOrder.getFormingMethod(),
            workOrder.getLayerCount(),
            workOrder.getProductionNoticeQuantity(),
            workOrder.getCustomerOrder(),
            workOrder.getCustomerOrderNo(),
            workOrder.getCustomerOrderQuantity(),
            workOrder.getMaterialArea(),
            workOrder.getProductionNoticeArea(),
            workOrder.getCustomerOrderArea(),
            workOrder.getTotalPanelQuantity(),
            workOrder.getABoardPanelQuantity(),
            workOrder.getBBoardPanelQuantity(),
            workOrder.getPanelizationNo(),
            workOrder.getEstimatedYieldRate(),
            workOrder.getPlannedMaterialIssueQuantity(),
            workOrder.getUpdatedAt(),
            batches.stream().map(BatchResponse::from).toList(),
            workOrder.getMaterialInputQuantity(),
            workOrder.getCumulativeScrapQuantity(),
            workOrder.getCumulativeDefectQuantity(),
            workOrder.getPnlLength(),
            workOrder.getPnlWidth(),
            workOrder.getProductionNoticeOrderQuantity(),
            workOrder.getUnreceivedQuantity(),
            workOrder.getLastWarehouseDate()
        );
    }

    public record BatchResponse(String id, String batchNo, Integer plannedQuantity, String status) {
        static BatchResponse from(ProductionBatch batch) {
            return new BatchResponse(batch.getId(), batch.getBatchNo(), batch.getPlannedQuantity(), batch.getStatus());
        }
    }
}
